"""Build reports/hw08/METRICS.md from the raw HW8 result files.

    python code/hw8/build_metrics.py

Reads raw/part1_demo.json, raw/part2_final.json, raw/failure_results.json,
the ordering CSVs and verification.json. Nothing is typed in by hand, so the
tables always match the saved runs.
"""

from __future__ import annotations

import csv
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from src.hw8_kafka.config import (  # noqa: E402
    DOMAIN_ID,
    PORT_BASE,
    PREFIX,
    SEED,
    SID4,
    TOPICS,
    VERIFY_SEED,
)

REPORT = ROOT / "reports" / "hw08"
RAW = REPORT / "raw"


def load(name: str):
    path = RAW / name if not name.startswith("..") else REPORT / name[3:]
    return json.loads(path.read_text()) if path.exists() else None


def ts(value: str) -> datetime:
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def main() -> int:
    md = [
        "# HW8 Metrics - Kazi Samina Maraj Mumu",
        "",
        "Generated by `python code/hw8/build_metrics.py` from `reports/hw08/raw/`.",
        "",
        "| SID4 | PORT_BASE | PREFIX | SEED | VERIFY_SEED | DOMAIN_ID |",
        "|---|---|---|---|---|---|",
        f"| {SID4} | {PORT_BASE} | {PREFIX} | {SEED} | {VERIFY_SEED} | {DOMAIN_ID} |",
        "",
        "## Topics",
        "",
        "| Topic | Partitions | Used by |",
        "|---|---|---|",
    ]
    users = {
        "entity_requests": "Part 1 client/API -> worker",
        "entity_responses": "Part 1 worker -> API (reply_to)",
        "inbox": "Part 2 send_question -> Planner",
        "tasks": "Part 2 Planner -> Writer (2 partitions, Part 3 ordering)",
        "drafts": "Part 2 Writer -> Reviewer",
        "final": "Part 2 Reviewer -> result",
        "dead_letter": "Part 3 poison messages",
    }
    for topic, parts in TOPICS.items():
        md.append(f"| `{topic}` | {parts} | {users[topic.split('_', 1)[1]]} |")

    p1 = load("part1_demo.json")
    md += ["", "## Part 1 - request/response over Kafka", ""]
    if p1:
        c, g = p1["create"], p1["get"]
        got_id = (g["response"].get("incident") or {}).get("incident_id")
        md += [
            "| Operation | correlation_id | success | result |",
            "|---|---|---|---|",
            f"| CREATE_INCIDENT | `{c['correlation_id']}` | {c['response']['success']} "
            f"| incident_id `{c['response'].get('incident_id')}` |",
            f"| GET_INCIDENT | `{g['correlation_id']}` | {g['response']['success']} "
            f"| returned incident_id `{got_id}` |",
            "",
            f"Round trip matches the created incident: **{p1['round_trip_ok']}**",
        ]
    else:
        md.append("_not run yet (python homework_demo.py)_")

    p2 = load("part2_final.json")
    md += ["", "## Part 2 - three-agent pipeline", ""]
    if p2:
        md += [
            f"correlation_id `{p2['correlation_id']}` - status **{p2.get('status')}**",
            "",
            "| Stage | Agent | Input topic[partition] | Offset | Time in stage (s) |",
            "|---|---|---|---|---|",
        ]
        for i, hop in enumerate(p2.get("trace", []), 1):
            secs = (ts(hop["sent_at"]) - ts(hop["received_at"])).total_seconds()
            md.append(
                f"| {i} | {hop['agent']} | {hop['in_topic']}[{hop['partition']}] "
                f"| {hop['offset']} | {secs:.2f} |"
            )
        trace = p2.get("trace", [])
        if trace:
            total = (
                ts(trace[-1]["sent_at"]) - ts(trace[0]["received_at"])
            ).total_seconds()
            md += ["", f"End-to-end (Planner receive -> Reviewer send): {total:.2f} s"]
        md += ["", f"Reviewer feedback: {p2.get('review', '')}"]
    else:
        md.append("_not run yet (python code/hw8/send_question.py)_")

    results = load("failure_results.json") or {}
    md += [
        "",
        "## Part 3 - failure table",
        "",
        "| Failure scenario | Before fix | After fix |",
        "|---|---|---|",
    ]
    rows = [
        ("duplicate", "Duplicate delivery (Part 1 worker, CREATE_INCIDENT replay)"),
        ("duplicate-agent", "Duplicate delivery (Writer, task replay)"),
        ("consumer-death", "Consumer killed mid-work"),
        ("poison", "Poison message"),
        ("ordering", "Two partitions/two consumers"),
    ]
    for key, label in rows:
        cells = []
        for mode in ("before", "after"):
            r = results.get(key, {}).get(mode)
            cells.append(f"{r['summary']} (run {r['run_id']})" if r else "not run")
        md.append(f"| {label} | {cells[0]} | {cells[1]} |")

    md += ["", "### Ordering runs (VERIFY_SEED = 264098)", ""]
    for mode, label in (("before", "nokey"), ("after", "keyed")):
        path = RAW / f"ordering_{mode}_{label}.csv"
        if not path.exists():
            continue
        rows_csv = list(csv.DictReader(path.open()))
        md += [
            f"**Run {mode} (key = {'incident_id' if mode == 'after' else 'none'})**",
            "",
            "| Incident | Partitions used | Processed seq order |",
            "|---|---|---|",
        ]
        for incident in sorted({r["incident_id"] for r in rows_csv}):
            mine = [
                r
                for r in rows_csv
                if r["incident_id"] == incident and r["processed_rank"]
            ]
            mine.sort(key=lambda r: int(r["processed_rank"]))
            parts = sorted({r["partition"] for r in mine})
            md.append(
                f"| {incident} | {', '.join(parts)} | {[int(r['seq']) for r in mine]} |"
            )
        md.append("")

    ver = load("../verification.json")
    md += ["## verification.json", ""]
    if ver:
        md.append(
            f"{ver['passed']}/{ver['total']} checks passed on commit "
            f"`{ver['commit_hash']}`"
        )
    else:
        md.append("_not run yet (make verify-hw08)_")

    (REPORT / "METRICS.md").write_text("\n".join(md) + "\n")
    print(f"wrote {REPORT / 'METRICS.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
